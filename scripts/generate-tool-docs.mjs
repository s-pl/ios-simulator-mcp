// Generates docs/assets/tools.js from the tools the built server actually
// publishes, so the reference on the documentation site can never drift from
// the code. Run with `npm run docs:tools` (builds first).
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';

import { loadConfig } from '../dist/config.js';
import { createContainer } from '../dist/container.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'docs', 'assets', 'tools.js');

const config = loadConfig({});
const container = createContainer(config);
const client = new Client({ name: 'docs-generator', version: '0.0.0' });
const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
await container.server.connect(serverTransport);
await client.connect(clientTransport);

const { tools } = await client.listTools();
const reference = tools.map((tool) => {
  const required = new Set(tool.inputSchema.required ?? []);
  return {
    name: tool.name,
    title: tool.title ?? tool.annotations?.title ?? tool.name,
    description: tool.description ?? '',
    readOnly: tool.annotations?.readOnlyHint === true,
    destructive: tool.annotations?.destructiveHint === true,
    parameters: Object.entries(tool.inputSchema.properties ?? {}).map(([name, schema]) => ({
      name,
      type: describeType(schema),
      required: required.has(name),
      description: schema.description ?? '',
    })),
  };
});

await client.close();
await container.dispose();

await mkdir(path.dirname(output), { recursive: true });
await writeFile(
  output,
  `// Generated by scripts/generate-tool-docs.mjs — do not edit by hand.\n` +
    `window.SERVER_VERSION = ${JSON.stringify(config.version)};\n` +
    `window.TOOLS = ${JSON.stringify(reference, null, 2)};\n`,
);
console.log(`Wrote ${reference.length} tools to ${path.relative(root, output)}`);

/** Short human readable type of a JSON Schema node. */
function describeType(schema) {
  if (schema.enum) {
    return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  }
  if (schema.type === 'array') {
    return `${describeType(schema.items ?? {})}[]`;
  }
  const range = [
    schema.minimum !== undefined ? `≥ ${schema.minimum}` : '',
    schema.maximum !== undefined ? `≤ ${schema.maximum}` : '',
  ].filter(Boolean);
  const base = schema.type ?? 'any';
  return range.length > 0 ? `${base} (${range.join(', ')})` : base;
}
