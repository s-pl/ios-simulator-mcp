/** Asks the real server, over an in-memory transport, which tools it exposes. */
async function listTools() {
  const container = createContainer(loadConfig({}));
  const client = new Client({ name: 'docs-generator', version: '0.0.0' });
  const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
  await container.server.connect(serverTransport);
  await client.connect(clientTransport);
  const result = await client.listTools();
  await client.close();
  await container.dispose();
  return result.tools;
}

function renderPage(language) {
  const remaining = new Map(tools.map((tool) => [tool.name, tool]));
  const sections = GROUPS.map((group) => ({
    id: group.id,
    tools: group.tools.flatMap((name) => {
      const tool = remaining.get(name);
      remaining.delete(name);
      return tool ? [tool] : [];
    }),
  }));
  if (remaining.size > 0) {
    sections.push({ id: 'other', tools: [...remaining.values()] });
  }

  return [
    language.generated,
    '',
    `# ${language.title}`,
    '',
    ...language.intro(tools.length),
    '',
    ...sections.flatMap((section) => [
      `## ${language.sections[section.id]}`,
      '',
      ...(language.notes[section.id] ? [language.notes[section.id], ''] : []),
      ...section.tools.flatMap((tool) => renderTool(tool, language)),
    ]),
  ].join('\n');
}

function renderTool(tool, language) {
  const required = new Set(tool.inputSchema.required ?? []);
  const parameters = Object.entries(tool.inputSchema.properties ?? {});
  const rows = parameters.map(
    ([name, schema]) =>
      `| \`${name}\` | ${code(describeType(schema))} | ${required.has(name) ? language.yes : language.no} | ${cell(schema.description ?? '')} |`,
  );
  return [
    `### ${tool.name}`,
    '',
    `**${escapeText(tool.title ?? tool.name)}** · ${behaviour(tool.annotations ?? {}, language)}`,
    '',
    // Two trailing spaces keep the line breaks of multi-line descriptions in Markdown.
    escapeText(tool.description ?? '').replaceAll('\n', '  \n'),
    '',
    ...(rows.length > 0
      ? [`| ${language.columns.join(' | ')} |`, '| --- | --- | --- | --- |', ...rows]
      : [language.noParameters]),
    '',
  ];
}

function behaviour(annotations, language) {
  if (annotations.destructiveHint) return language.behaviour.destructive;
  return annotations.readOnlyHint ? language.behaviour.readOnly : language.behaviour.mutating;
}

/** Short human readable type of a JSON Schema node. */
function describeType(schema) {
  if (schema.enum) {
    return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  }
  if (schema.type === 'array') {
    return `${describeType(schema.items ?? {})}[]`;
  }
  const range = [
    schema.minimum !== undefined ? `>= ${schema.minimum}` : '',
    schema.maximum !== undefined ? `<= ${schema.maximum}` : '',
  ].filter(Boolean);
  const base = schema.type ?? (schema.anyOf ? 'object' : 'any');
  return range.length > 0 ? `${base} (${range.join(', ')})` : base;
}

/** Keeps Markdown and Vue from interpreting characters of free text. */
function escapeText(value) {
  return value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('{{', '&#123;&#123;');
}

/** Free text placed inside a table cell. */
function cell(value) {
  return escapeText(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

/** Inline code placed inside a table cell. */
function code(value) {
  return `\`${value.replaceAll('|', '\\|')}\``;
}
